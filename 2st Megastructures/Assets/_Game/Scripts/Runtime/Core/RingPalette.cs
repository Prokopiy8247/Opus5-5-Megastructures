        static Dictionary<string, Color> _lin;

        public static float SrgbToLinear(float c) => c <= 0.04045f ? c / 12.92f : Mathf.Pow((c + 0.055f) / 1.055f, 2.4f);
        public static float LinearToSrgb(float c) => c <= 0.0031308f ? c * 12.92f : 1.055f * Mathf.Pow(c, 1f / 2.4f) - 0.055f;

        public static Color HexToSrgb(string hex)
        {
            int v = int.Parse(hex, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
            return new Color(((v >> 16) & 255) / 255f, ((v >> 8) & 255) / 255f, (v & 255) / 255f, 1f);
        }

        public static Color HexToLinear(string hex)
        {
            var c = HexToSrgb(hex);
            return new Color(SrgbToLinear(c.r), SrgbToLinear(c.g), SrgbToLinear(c.b), 1f);
        }

        /// <summary>Linear RGB of a palette token (KeyError if the token does not exist).</summary>
        public static Color Lin(string name)
        {
            if (_lin == null)
            {
                _lin = new Dictionary<string, Color>();
                foreach (var e in Entries) _lin[e.name] = HexToLinear(e.hex);
            }
            return _lin[name];
        }

        public static Color Lin(string name, float hdr) { var c = Lin(name); return new Color(c.r * hdr, c.g * hdr, c.b * hdr, 1f); }

        /// <summary>HLSL include text: one static const float3 PAL_&lt;Name&gt; per token, linear RGB.</summary>
        public static string GenerateHlsl()
        {
            var sb = new StringBuilder();
            sb.AppendLine("// GENERATED by RingPalette.GenerateHlsl() (Tools/Megastructure/Rebuild All). Do not edit by hand.");
            sb.AppendLine("#ifndef RING_PALETTE_INCLUDED");
            sb.AppendLine("#define RING_PALETTE_INCLUDED");
            foreach (var e in Entries)
            {
                var c = HexToLinear(e.hex);
                sb.AppendFormat(CultureInfo.InvariantCulture, "static const float3 PAL_{0} = float3({1:0.000000}, {2:0.000000}, {3:0.000000}); // #{4}\n", e.name, c.r, c.g, c.b, e.hex);
            }
            sb.AppendLine("#endif");
            return sb.ToString();
        }
    }
