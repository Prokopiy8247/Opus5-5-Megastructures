#!/usr/bin/env python3
"""Bootstrap generator for Assets/_Game/Shaders/Generated/ThreadPalette.hlsl and ThreadConstantsGen.hlsl.

The authoritative generator is the editor script (Megastructure.EditorTools.ShaderGen, run by
RebuildAll); this script produces byte-identical output so shaders compile before the first
RebuildAll. Both read the same C# sources (ThreadPalette.Table, ThreadConstants const fields).
Usage: python -I Tools/gen_hlsl.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORE = os.path.join(ROOT, "Assets", "_Game", "Scripts", "Runtime", "Core")
OUT = os.path.join(ROOT, "Assets", "_Game", "Shaders", "Generated")


def srgb_to_linear(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def f6(v):
    # formatting identical to the C# generator: "0.######" invariant, trailing zeros trimmed, at least one decimal
    s = f"{v:.6f}".rstrip("0")
    if s.endswith("."):
        s += "0"
    return s


def palette():
    with open(os.path.join(CORE, "ThreadPalette.cs"), encoding="utf-8") as f:
        text = f.read()
    pairs = re.findall(r"\(Pal\.(\w+),\s*\"#([0-9A-Fa-f]{6})\"\)", text)
    lines = ["// GENERATED by RebuildAll (ShaderGen) from ThreadPalette.Table - do not edit.",
             "#ifndef THREAD_PALETTE_INCLUDED", "#define THREAD_PALETTE_INCLUDED"]
    for name, hx in pairs:
        r, g, b = (int(hx[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
        lin = [srgb_to_linear(c) for c in (r, g, b)]
        lines.append(f"#define PAL_{name} float3({f6(lin[0])}, {f6(lin[1])}, {f6(lin[2])})")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def constants():
    with open(os.path.join(CORE, "ThreadConstants.cs"), encoding="utf-8") as f:
        text = f.read()
    lines = ["// GENERATED by RebuildAll (ShaderGen) from ThreadConstants - do not edit.",
             "#ifndef THREAD_CONSTANTS_INCLUDED", "#define THREAD_CONSTANTS_INCLUDED"]
    for m in re.finditer(r"public const (double|float|int) ([^;]+);", text):
        decls = m.group(2)
        for part in re.split(r",\s*(?=\w+\s*=)", decls):
            name, val = [x.strip() for x in part.split("=")]
            val = val.rstrip("f")
            v = float(val)
            lines.append(f"#define TC_{name} {f6(v)}")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main():
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "ThreadPalette.hlsl"), "w", encoding="utf-8", newline="\n") as f:
        f.write(palette())
    with open(os.path.join(OUT, "ThreadConstantsGen.hlsl"), "w", encoding="utf-8", newline="\n") as f:
        f.write(constants())
    print("written", OUT)


if __name__ == "__main__":
    main()
