// ShaderGen: the authoritative generator of Assets/_Game/Shaders/Generated/ThreadPalette.hlsl (PAL_* macros,
// MASTER_PROMPT 14.7.8) and ThreadConstantsGen.hlsl (TC_* macros for every public const double/float/int of
// ThreadConstants). The output is BYTE-IDENTICAL to Tools/gen_hlsl.py (the bootstrap generator):
//   - same header lines, LF line endings, UTF-8 without BOM, trailing newline;
//   - values formatted by the "f6" rule: Python f"{v:.6f}" (correctly rounded, ties to even, on the exact
//     binary value of the double), trailing zeros trimmed, at least one decimal;
//   - palette values in double: srgb_to_linear(int(hex)/255.0) with the piecewise sRGB EOTF;
//   - constants in declaration order (metadata order of the const fields); a float const is first turned
//     into its shortest round-trip decimal string, because Python parses the literal text as a double.
// ProjectTests verifies the equality against a run of the Python script and against the files on disk.
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Numerics;
using System.Reflection;
using System.Text;
using UnityEditor;

namespace Megastructure.EditorTools
{
    public static class ShaderGen
    {
        static readonly UTF8Encoding s_Utf8NoBom = new UTF8Encoding(false);
        static readonly BigInteger s_Million = new BigInteger(1000000);

        /// <summary>Exact port of gen_hlsl.py f6(): "{v:.6f}" with trailing zeros trimmed, at least one decimal.</summary>
        public static string F6(double v)
        {
            if (double.IsNaN(v) || double.IsInfinity(v)) throw new ArgumentException("F6: value is not finite: " + v.ToString(CultureInfo.InvariantCulture));
            long bits = BitConverter.DoubleToInt64Bits(v);
            bool negative = bits < 0;                       // Python keeps the sign of -0.0 and of values that round to 0
            int exponent = (int)((bits >> 52) & 0x7FF);
            long mantissa = bits & 0xFFFFFFFFFFFFFL;
            if (exponent == 0) exponent = 1;                // subnormal: m * 2^(1 - 1075)
            else mantissa |= 1L << 52;
            int e2 = exponent - 1075;                       // |v| = mantissa * 2^e2 exactly

            BigInteger num = new BigInteger(mantissa) * s_Million;   // |v| * 10^6 = num * 2^e2
            BigInteger q;
            if (e2 >= 0) q = num << e2;
            else
            {
                BigInteger den = BigInteger.One << (-e2);
                q = BigInteger.DivRem(num, den, out BigInteger rem);
                int c = (rem << 1).CompareTo(den);
                if (c > 0 || (c == 0 && !q.IsEven)) q += BigInteger.One;   // round half to even (Python's dtoa)
            }
            BigInteger ip = BigInteger.DivRem(q, s_Million, out BigInteger fp);
            string s = (negative ? "-" : "") + ip.ToString(CultureInfo.InvariantCulture) + "." +
                       fp.ToString(CultureInfo.InvariantCulture).PadLeft(6, '0');
            s = s.TrimEnd('0');
            if (s.EndsWith(".", StringComparison.Ordinal)) s += "0";
            return s;
        }

        /// <summary>Content of Generated/ThreadPalette.hlsl.</summary>
        public static string PaletteHlsl()
        {
            var sb = new StringBuilder(4096);
            sb.Append("// GENERATED by RebuildAll (ShaderGen) from ThreadPalette.Table - do not edit.\n");
            sb.Append("#ifndef THREAD_PALETTE_INCLUDED\n");
            sb.Append("#define THREAD_PALETTE_INCLUDED\n");
            var table = ThreadPalette.Table;
            for (int i = 0; i < table.Length; i++)
            {
                string h = table[i].hex.TrimStart('#');
                double r = ThreadPalette.SrgbToLinear(Convert.ToInt32(h.Substring(0, 2), 16) / 255.0);
                double g = ThreadPalette.SrgbToLinear(Convert.ToInt32(h.Substring(2, 2), 16) / 255.0);
                double b = ThreadPalette.SrgbToLinear(Convert.ToInt32(h.Substring(4, 2), 16) / 255.0);
                sb.Append("#define PAL_").Append(table[i].id.ToString()).Append(" float3(")
                  .Append(F6(r)).Append(", ").Append(F6(g)).Append(", ").Append(F6(b)).Append(")\n");
            }
            sb.Append("#endif\n");
            return sb.ToString();
        }

        /// <summary>The const fields exported as TC_* macros, in declaration order.</summary>
        public static List<FieldInfo> ExportedConstants()
        {
            var fields = new List<FieldInfo>();
            foreach (var f in typeof(ThreadConstants).GetFields(BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly))
            {
                if (!f.IsLiteral || f.IsInitOnly) continue;
                var ft = f.FieldType;
                if (ft == typeof(double) || ft == typeof(float) || ft == typeof(int)) fields.Add(f);
            }
            // Metadata order is declaration order for fields emitted by Roslyn; sort explicitly so the result
            // does not depend on the runtime's reflection ordering.
            fields.Sort((a, b) => a.MetadataToken.CompareTo(b.MetadataToken));
            return fields;
        }

        /// <summary>The value Python's float(literal) would produce for this const field.</summary>
        public static double ConstantAsPythonDouble(FieldInfo f)
        {
            object raw = f.GetRawConstantValue();
            if (raw is double d) return d;
            if (raw is int i) return i;
            if (raw is float fl)
            {
                // Shortest round-trip text of the float = the source literal for every literal with <= 9 significant digits.
                string txt = fl.ToString("R", CultureInfo.InvariantCulture);
                return double.Parse(txt, NumberStyles.Float, CultureInfo.InvariantCulture);
            }
            throw new InvalidOperationException("ShaderGen: unsupported const type " + f.FieldType.Name + " for " + f.Name);
        }

        /// <summary>Content of Generated/ThreadConstantsGen.hlsl.</summary>
        public static string ConstantsHlsl()
        {
            var sb = new StringBuilder(16384);
            sb.Append("// GENERATED by RebuildAll (ShaderGen) from ThreadConstants - do not edit.\n");
            sb.Append("#ifndef THREAD_CONSTANTS_INCLUDED\n");
            sb.Append("#define THREAD_CONSTANTS_INCLUDED\n");
            var fields = ExportedConstants();
            for (int i = 0; i < fields.Count; i++)
                sb.Append("#define TC_").Append(fields[i].Name).Append(' ').Append(F6(ConstantAsPythonDouble(fields[i]))).Append('\n');
            sb.Append("#endif\n");
            return sb.ToString();
        }

        public static byte[] Encode(string text) => s_Utf8NoBom.GetBytes(text);

        /// <summary>Writes both files (only when the bytes differ, so an unchanged run triggers no reimport).</summary>
        public static int WriteAll()
        {
            EditorUtil.EnsureFolder(ThreadPaths.GeneratedDir);
            int changed = 0;
            changed += WriteIfChanged(ThreadPaths.PaletteHlsl, PaletteHlsl());
            changed += WriteIfChanged(ThreadPaths.ConstantsHlsl, ConstantsHlsl());
            ThreadLog.Info($"ShaderGen: {ThreadPalette.Table.Length} PAL_ tokens, {ExportedConstants().Count} TC_ constants, {changed} file(s) changed");
            return changed;
        }

        static int WriteIfChanged(string assetPath, string text)
        {
            string abs = ThreadPaths.Abs(assetPath);
            byte[] bytes = Encode(text);
            if (File.Exists(abs))
            {
                byte[] old = File.ReadAllBytes(abs);
                if (BytesEqual(old, bytes)) return 0;
            }
            File.WriteAllBytes(abs, bytes);
            AssetDatabase.ImportAsset(assetPath, ImportAssetOptions.ForceSynchronousImport);
            ThreadLog.Info("ShaderGen: wrote " + assetPath);
            return 1;
        }

        public static bool BytesEqual(byte[] a, byte[] b)
        {
            if (a == null || b == null || a.Length != b.Length) return false;
            for (int i = 0; i < a.Length; i++) if (a[i] != b[i]) return false;
            return true;
        }
    }
}
